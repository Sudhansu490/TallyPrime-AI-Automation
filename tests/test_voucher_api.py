"""Voucher generation through the API, with SYNTHETIC documents and SYNTHETIC TallyPrime masters."""

from __future__ import annotations

import pytest
from fastapi.testclient import TestClient

from extraction_fakes import (
    INVOICE_TEXT, STATEMENT_PAGE_1, STATEMENT_PAGE_2, FakeLlm, field, invoice_reply, statement_page1_reply,
    statement_page2_reply,
)
from tally_fakes import COMPANY, COMPANY_GUID, FakeTally, LEDGERS
from tally_fakes import _envelope as envelope
from tally_fakes import _ledger as ledger
from tally_automation.tally.xmlio import TallyWriteBlocked, assert_read_only
from test_extraction_api import process, text_pdf, upload

EXTRA_LEDGERS = (
    ledger("Input IGST 18%", "Duties &amp; Taxes", "<GSTDUTYHEAD>IGST</GSTDUTYHEAD><RATEOFTAXCALCULATION> 18</RATEOFTAXCALCULATION>",
           tax_type="GST")
    + ledger("Synthetic Cash", "Cash-in-Hand")
)
VOUCHER_TYPES = envelope("".join(
    f'<VOUCHERTYPE NAME="{n}"><GUID>v-{n}</GUID><PARENT>{n}</PARENT><NUMBERINGMETHOD>Automatic</NUMBERINGMETHOD>'
    "<ISACTIVE>Yes</ISACTIVE></VOUCHERTYPE>\n" for n in ("Purchase", "Payment", "Receipt", "Contra")
))
TAXED = {"header": {"total_taxable_value": field("1,000.00"), "total_igst": field("180.00")}}


@pytest.fixture
def tally(client: TestClient) -> FakeTally:
    fake = FakeTally()
    fake.overrides["Ledger"] = LEDGERS.replace("   </COLLECTION>", EXTRA_LEDGERS + "   </COLLECTION>")
    fake.overrides["VoucherType"] = VOUCHER_TYPES
    client.app.state.settings.tally_host = "127.0.0.1"
    client.app.state.tally_transport = fake.transport
    assert client.post("/api/v1/tally/sync", json={"company": COMPANY}).status_code == 200
    fake.requests.clear()
    return fake


def guid(name: str) -> str:
    return f"l-{name}"


def setup(client: TestClient, document_id: int) -> dict:
    response = client.get(f"/api/v1/documents/{document_id}/voucher-setup")
    assert response.status_code == 200, response.text
    return response.json()


def invoice_document(client: TestClient, **overrides) -> int:
    document_id = upload(client, text_pdf(INVOICE_TEXT))
    process(client, FakeLlm(invoice_reply(**(overrides or TAXED))))
    return document_id


def invoice_choice(**override) -> dict:
    choice = {"voucher_type": "Purchase", "party": guid("Synthetic Supplier Pvt Ltd"),
              "purchase": {"18": guid("Synthetic Office Supplies")}, "duty": {"IGST": guid("Input IGST 18%")}}
    choice.update(override)
    return choice


def generate(client: TestClient, document_id: int, **body):
    return client.post(f"/api/v1/documents/{document_id}/vouchers", json={"company_guid": COMPANY_GUID, **body})


def test_invoice_setup_suggests_but_does_not_decide(client: TestClient, tally: FakeTally) -> None:
    document_id = invoice_document(client)
    body = setup(client, document_id)
    assert body["eligibility"]["eligible"] and body["company"]["guid"] == COMPANY_GUID
    inv = body["invoice"]
    assert [(b["key"], b["taxable"]) for b in inv["buckets"]] == [("18", "1000.00")]
    assert inv["taxes"] == [{"head": "IGST", "amount": "180.00"}]
    s = body["suggestions"]
    assert [(p["name"], p["reason"]) for p in s["party"]] == [("Synthetic Supplier Pvt Ltd", "Same GSTIN as the invoice")]
    assert s["duty"]["IGST"][0]["name"] == "Input IGST 18%"
    assert [v["name"] for v in s["voucher_types"]["purchase"]] == ["Purchase"]
    assert client.get(f"/api/v1/documents/{document_id}/vouchers").json() == []    # nothing generated by looking


def test_generate_purchase_voucher_sends_nothing_to_tally(client: TestClient, tally: FakeTally) -> None:
    document_id = invoice_document(client)
    response = generate(client, document_id, invoice=invoice_choice())
    assert response.status_code == 200, response.text
    [voucher] = response.json()
    assert (voucher["status"], voucher["error_count"], voucher["voucher_kind"], voucher["amount"]) == ("ready", 0, "purchase", "1180.00")
    assert [(e["role"], e["debit"], e["credit"]) for e in voucher["entries"]] == [
        ("party", None, "1180.00"), ("purchase", "1000.00", None), ("duty:IGST", "180.00", None)]
    assert voucher["reference"] == "SYN-0001" and voucher["voucher_date"] == "2026-04-01"
    assert voucher["marker"].startswith("TA-") and voucher["stale_reasons"] == []
    assert any(c["code"] == "xml_structure" and c["passed"] for c in voucher["checks"])
    assert tally.requests == []                                   # generation never contacts TallyPrime

    detail = client.get(f"/api/v1/vouchers/{voucher['id']}").json()
    assert "<TALLYREQUEST>Import Data</TALLYREQUEST>" in detail["xml"] and len(detail["xml_sha256"]) == 64
    with pytest.raises(TallyWriteBlocked):
        assert_read_only(detail["xml"])

    # Chosen ledgers come back as suggestions next time; the party is no longer ambiguous.
    again = setup(client, document_id)["suggestions"]
    assert again["party"][0]["reason"] == "Chosen last time"
    assert again["purchase"]["18"][0]["name"] == "Synthetic Office Supplies"


def test_generating_again_supersedes_and_edits_make_vouchers_stale(client: TestClient, tally: FakeTally) -> None:
    document_id = invoice_document(client)
    first = generate(client, document_id, invoice=invoice_choice()).json()[0]
    second = generate(client, document_id, invoice=invoice_choice()).json()[0]
    current = client.get(f"/api/v1/documents/{document_id}/vouchers").json()
    assert [v["id"] for v in current] == [second["id"]]
    every = client.get(f"/api/v1/documents/{document_id}/vouchers?include_superseded=true").json()
    assert {v["id"]: v["status"] for v in every} == {first["id"]: "superseded", second["id"]: "ready"}

    invoice_id = client.get(f"/api/v1/documents/{document_id}/extraction").json()["data"]["id"]
    client.patch(f"/api/v1/extractions/invoice/{invoice_id}/fields/purchase_order_number", json={"value": "PO-9"})
    stale = client.get(f"/api/v1/vouchers/{second['id']}").json()["stale_reasons"]
    assert stale == ["The extracted data was edited since; generate the voucher again."]

    client.post("/api/v1/tally/sync", json={"company": COMPANY})
    assert any("retrieved again" in r for r in client.get(f"/api/v1/vouchers/{second['id']}").json()["stale_reasons"])


def test_wrong_ledgers_produce_a_blocked_voucher(client: TestClient, tally: FakeTally) -> None:
    document_id = invoice_document(client)
    [voucher] = generate(client, document_id, invoice=invoice_choice(
        party=guid("Input IGST 18%"), duty={"IGST": guid("Input CGST 9%")}, voucher_type="Payment")).json()
    assert voucher["status"] == "blocked" and voucher["error_count"] >= 3
    failing = {c["code"] for c in voucher["checks"] if not c["passed"] and c["severity"] == "error"}
    assert {"party_ledger_kind", "duty_ledger_head", "voucher_type_base"} <= failing


@pytest.mark.parametrize(("choice", "code"), [
    (invoice_choice(duty={}), "mapping_incomplete"),
    (invoice_choice(party="l-no such ledger"), "unknown_ledger"),
])
def test_incomplete_or_unknown_choices_are_refused(client: TestClient, tally: FakeTally, choice: dict, code: str) -> None:
    document_id = invoice_document(client)
    response = generate(client, document_id, invoice=choice)
    assert response.status_code == 422 and response.json()["code"] == code
    assert client.get(f"/api/v1/documents/{document_id}/vouchers").json() == []


def test_ineligible_documents_get_no_voucher(client: TestClient, tally: FakeTally) -> None:
    bad = upload(client, text_pdf(INVOICE_TEXT))
    process(client, FakeLlm(invoice_reply(header={**TAXED["header"], "grand_total": field("1,280.00")})))
    response = generate(client, bad, invoice=invoice_choice())
    assert response.status_code == 409 and response.json()["code"] == "not_eligible"
    assert "validation error" in response.json()["detail"]
    assert client.get("/api/v1/documents/999/voucher-setup").status_code == 404


def test_masters_are_required(client: TestClient) -> None:
    document_id = invoice_document(client)
    response = generate(client, document_id, invoice=invoice_choice())
    assert response.status_code == 409 and response.json()["code"] == "no_masters"
    body = setup(client, document_id)
    assert body["company"] is None and body["suggestions"] is None


def test_statement_vouchers_mask_the_account_and_pick_contra(client: TestClient, tally: FakeTally) -> None:
    document_id = upload(client, text_pdf(STATEMENT_PAGE_1, STATEMENT_PAGE_2), "bank_statement")
    process(client, FakeLlm(statement_page1_reply(), statement_page2_reply()), pages_per_call=1)
    response = client.get(f"/api/v1/documents/{document_id}/voucher-setup")
    body = response.json()
    assert "123456789012" not in response.text and body["statement"]["account_number"] == "XXXXXXXX9012"
    assert body["suggestions"]["bank"][0]["name"] == "Synthetic Bank"
    out, into = body["statement"]["transactions"]
    assert (out["money_out"], out["amount"], into["money_out"]) == (True, "5000.00", False)

    vouchers = generate(client, document_id, statement={
        "bank": guid("Synthetic Bank"),
        "voucher_types": {"payment": "Payment", "receipt": "Receipt", "contra": "Contra"},
        "transactions": [{"transaction_id": out["id"], "ledger": guid("Synthetic Supplier Pvt Ltd")},
                         {"transaction_id": into["id"], "ledger": guid("Synthetic Cash")}],
    })
    assert vouchers.status_code == 200, vouchers.text
    payment, contra = vouchers.json()
    assert (payment["voucher_kind"], payment["status"], contra["voucher_kind"], contra["status"]) == (
        "payment", "ready", "contra", "ready")
    assert [(e["role"], e["debit"]) for e in payment["entries"]] == [("counter", "5000.00"), ("bank", None)]
    assert payment["source_label"] == "Transaction 1" and "NEFT SYNTHETIC VENDOR" in payment["narration"]
    detail = client.get(f"/api/v1/vouchers/{payment['id']}")
    assert "123456789012" not in detail.text and tally.requests == []
    assert setup(client, document_id)["suggestions"]["counter"][str(out["id"])][0]["reason"] == "Chosen last time"
    assert {v["id"] for v in client.get("/api/v1/vouchers").json()} == {payment["id"], contra["id"]}


def test_generation_rejects_cross_site_requests(client: TestClient, tally: FakeTally) -> None:
    document_id = invoice_document(client)
    response = client.post(f"/api/v1/documents/{document_id}/vouchers", headers={"Origin": "https://evil.example"},
                           json={"company_guid": COMPANY_GUID, "invoice": invoice_choice()})
    assert response.status_code == 403
    assert client.get(f"/api/v1/documents/{document_id}/vouchers").json() == []
